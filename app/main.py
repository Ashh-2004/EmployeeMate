# Request ID & Logging Middleware
@app.middleware("http")
async def logging_request_id_middleware(request: Request, call_next):
    req_id = request.headers.get("X-Request-ID") or str(uuid.uuid4())
    request_id_var.set(req_id)
    start_time = time.time()

    response = await call_next(request)
    latency_ms = (time.time() - start_time) * 1000

    logger.info(
        f"HTTP {request.method} {request.url.path} -> {response.status_code} ({latency_ms:.1f}ms)"
    )
    response.headers["X-Request-ID"] = req_id
    return response


# Request & Response Models
class ChatRequest(BaseModel):
    prompt: Optional[str] = Field(None, max_length=2000, description="User query or instruction", example="What is the WFH policy?")
    message: Optional[str] = Field(None, max_length=2000, description="Alternative field for user query")

    emp_id: Optional[str] = Field(None, description="Optional Employee ID for HR context", example="EMP001")
    employee_id: Optional[str] = Field(None, description="Alternative field for Employee ID")

    actor_role: Optional[str] = Field("EMPLOYEE", description="Role of the user (ignored for auth)", example="EMPLOYEE")
    session_id: Optional[str] = Field(None, description="Optional conversation session ID")
    category: Optional[str] = Field(None, description="Optional explicit metadata category filter")
    history: Optional[List[dict]] = Field(default_factory=list, description="Recent conversation history")

    @model_validator(mode="after")
    def normalize_assessment_fields(self):
        if not self.prompt and self.message:
            self.prompt = self.message

        if not self.emp_id and self.employee_id:
            self.emp_id = self.employee_id

        if not self.prompt:
            raise ValueError("Either 'prompt' or 'message' is required.")

        return self


class ChatResponse(BaseModel):
    answer: str = Field(..., description="Final answer generated by the system")
    sources: List[str] = Field(default_factory=list, description="List of source policy files retrieved by RAG")
    tools_used: List[str] = Field(default_factory=list, description="List of tools/methods executed during request")
    agent_routed: str = Field(..., description="The name of the agent or orchestrator handling the request")
    updated_employees: Optional[List[dict]] = Field(None, description="Live updated employee profiles state")


# Global Exception Handling
@app.exception_handler(Exception)
async def global_exception_handler(request: Request, exc: Exception):
    req_id = request_id_var.get("")
    logger.exception(f"[Unhandled Server Exception] {exc}")
    return JSONResponse(
        status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
        content={
            "detail": "An internal server error occurred.",
            "request_id": req_id,
            "type": exc.__class__.__name__
        }
    )


# --- Core Logic Functions ---
def execute_health_check():
    provider = (getattr(settings, "llm_provider", "ollama") or "ollama").lower().strip()
    if provider == "gemini":
        model = getattr(settings, "gemini_model", "gemini-3.6-flash")
    elif provider == "openai":
        model = getattr(settings, "openai_model", "gpt-4o-mini")
    else:
        model = getattr(settings, "lmstudio_model", "gemma4:latest")
    return {
        "status": "healthy",
        "app_env": getattr(settings, "app_env", "production"),
        "vector_store_initialized": orchestrator.knowledge_agent.rag.vector_store is not None,
        "llm_provider": provider,
        "llm_model": model
    }


def execute_get_employees():
    return orchestrator.hr_agent.db.get_all_employees()


def execute_chat(request_payload: ChatRequest, current_user: Optional[Principal] = None):
    if not request_payload.prompt or not request_payload.prompt.strip():
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Prompt field cannot be empty."
        )

    try:
        # User principal defaults or overrides
        user_emp = current_user.emp_id if current_user else (request_payload.emp_id or "EMP001")
        user_role = current_user.role if current_user else (request_payload.actor_role or "EMPLOYEE").upper()
        principal = current_user or Principal(emp_id=user_emp, role=user_role)

        # Retrieve server-side history if payload history is empty
        history_to_use = request_payload.history or memory_store.get_history(principal.emp_id, request_payload.session_id)

        result = orchestrator.route_and_execute(
            prompt=request_payload.prompt,
            emp_id=principal.emp_id,
            history=history_to_use,
            principal=principal,
            actor_role=principal.role,
            category=request_payload.category
        )

        # Update server-side memory
        memory_store.add_turn(principal.emp_id, request_payload.session_id, "user", request_payload.prompt)
        memory_store.add_turn(principal.emp_id, request_payload.session_id, "assistant", result["answer"])

        # Filter updated_employees for non-HR callers
        live_employees = orchestrator.hr_agent.db.get_all_employees()["data"]
        if principal.role != "HR":
            live_employees = [e for e in live_employees if e["emp_id"].upper() == principal.emp_id.upper()]

        return ChatResponse(
            answer=result["answer"],
            sources=result.get("sources", []),
            tools_used=result.get("tools_used", []),
            agent_routed=result.get("agent_routed", "Unknown"),
            updated_employees=live_employees
        )
    except HTTPException:
        raise
    except Exception as e:
        logger.exception(f"[execute_chat Error] {e}")
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Error processing chat request: {str(e)}"
        )


# --- Auth Routes ---
@app.post("/auth/login", response_model=AuthTokenResponse, tags=["Authentication"])
async def login(login_req: AuthLoginRequest):
    emp_clean = login_req.emp_id.strip().upper()
    emp_res = orchestrator.hr_agent.db.get_employee_info(emp_clean)
    if emp_res["status"] == "error":
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail=f"Invalid employee credentials for '{emp_clean}'"
        )

    emp_data = emp_res["data"]
    role = emp_data.get("role", "EMPLOYEE")
    # Assign HR role for EMP002 or HR department
    if emp_clean == "EMP002" or emp_data.get("department") == "HR":
        role = "HR"
    else:
        role = "EMPLOYEE"

    expected_pwd = settings.demo_hr_password if role == "HR" else settings.demo_employee_password
    if login_req.password != expected_pwd:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Invalid employee credentials (incorrect password)"
        )

    token = create_access_token(emp_clean, role)
    return AuthTokenResponse(
        access_token=token,
        token_type="bearer",
        emp_id=emp_clean,
        role=role,
        name=emp_data.get("name", emp_clean)
    )


