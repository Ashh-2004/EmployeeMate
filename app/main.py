@app.post("/chat/stream", tags=["Chat Assistant"])
def chat_stream(request_payload: ChatRequest, current_user: Principal = Depends(get_current_user)):
    """POST /chat/stream Endpoint - True SSE token streaming with JWT authentication."""
    def event_generator():
        try:
            # Check for pure policy queries vs HR queries
            user_emp = current_user.emp_id
            principal = current_user
            history_to_use = request_payload.history or memory_store.get_history(user_emp, request_payload.session_id)

            # Pre-check for prompt injection
            from app.security import detect_prompt_injection, normalize_input
            norm_prompt = normalize_input(request_payload.prompt)
            is_inj, pattern = detect_prompt_injection(norm_prompt)
            if is_inj:
                meta = {
                    "type": "metadata",
                    "sources": [],
                    "tools_used": [],
                    "agent_routed": "Guardrail",
                    "updated_employees": []
                }
                yield f"data: {json.dumps(meta)}\n\n"
                yield f"data: {json.dumps({'type': 'token', 'token': 'I cannot fulfill this request because it violates safety guidelines.'})}\n\n"
                yield "data: [DONE]\n\n"
                return

            # Check if intent routes strictly to RAG or HR
            from app.conversation import rewrite_followup
            from app.rag import get_llm
            standalone = rewrite_followup(norm_prompt, history_to_use, llm=get_llm())
            
            prompt_lower = standalone.lower()
            is_hr_intent = bool("leave" in prompt_lower or "balance" in prompt_lower or "emp" in prompt_lower)

            if not is_hr_intent:
                # Stream RAG query tokens
                for stream_event in orchestrator.knowledge_agent.rag.stream_query(
                    query_text=standalone,
                    category=request_payload.category,
                    emp_id=user_emp,
                    history=history_to_use
                ):
                    yield f"data: {json.dumps(stream_event)}\n\n"
                yield "data: [DONE]\n\n"
                return

            # Synchronous fall-through for HR operations
            res = execute_chat(request_payload, current_user=current_user)
            meta = {
                "type": "metadata",
                "sources": res.sources,
                "tools_used": res.tools_used,
                "agent_routed": res.agent_routed,
                "updated_employees": res.updated_employees
            }
            yield f"data: {json.dumps(meta)}\n\n"
            yield f"data: {json.dumps({'type': 'token', 'token': res.answer})}\n\n"
            yield "data: [DONE]\n\n"
        except Exception as e:
            logger.exception(f"[SSE Stream Error] {e}")
            yield f"data: {json.dumps({'type': 'error', 'error': str(e)})}\n\n"

    return StreamingResponse(event_generator(), media_type="text/event-stream")


